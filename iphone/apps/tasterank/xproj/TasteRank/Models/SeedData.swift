    private static func restaurant(
        id: String,
        name: String,
        cuisine: CuisineTag,
        neighborhood: Neighborhood,
        priceLevel: Int,
        blurb: String,
        dishes: [String],
        distanceMiles: Double,
        hours: OpenHours,
        seedRating: Double,
        popularity: Int,
        photoSeed: String,
        isNew: Bool,
        isTrending: Bool,
        locationLine: String,
        cuisineDetails: String,
        statusLine: String,
        beliScore: Double,
        photoAssetNames: [String],
        searchHints: [String]
    ) -> Restaurant {
        Restaurant(
            id: id,
            name: name,
            cuisine: cuisine,
            neighborhood: neighborhood,
            priceLevel: priceLevel,
            blurb: blurb,
            dishes: dishes.enumerated().map { Dish(id: "\(id)_dish_\($0.offset)", name: $0.element) },
