            photoSeed: photoSeed,
            isNew: isNew,
            isTrending: isTrending,
            locationLine: locationLine,
            cuisineDetails: cuisineDetails,
            statusLine: statusLine,
            beliScore: beliScore,
            photoAssetNames: photoAssetNames,
            searchHints: searchHints
        )
    }

