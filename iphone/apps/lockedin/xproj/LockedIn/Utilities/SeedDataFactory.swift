    // MARK: - Seed Comments

    static func makeSeedComments(for posts: [Post], connections: [Connection]) -> [String: [PostComment]] {
        var result: [String: [PostComment]] = [:]
        let commentTexts = [
            "Great insights! Thanks for sharing.",
            "This is so relevant to what we're working on right now.",
            "Couldn't agree more. Well said!",
            "Really interesting perspective. I've seen similar patterns in my work.",
            "This resonates a lot. We faced the same challenges last quarter.",
            "Thanks for putting this into words. Sharing with my team!",
            "Love this take. The industry definitely needs more of this thinking.",
            "Spot on! We implemented something similar and saw great results.",
            "This is a must-read for anyone in the space.",
            "Great point about the tooling. That's often the bottleneck.",
            "Bookmarking this for our next planning session.",
            "Totally agree. The shift toward this approach has been transformative.",
            "Would love to hear more about how you measured the impact.",
            "Fascinating. We should connect and chat more about this!",
            "This aligns perfectly with what I've been advocating for.",
        ]
        for post in posts where post.commentCount > 0 {
            let numComments = min(post.commentCount, 8)
            var comments: [PostComment] = []
            for i in 0..<numComments {
                let conn = connections[i % connections.count]
                let text = commentTexts[i % commentTexts.count]
                comments.append(PostComment(
                    id: "seed_comment_\(post.id)_\(i)",
                    authorName: conn.fullName,
                    authorHeadline: conn.headline,
                    authorInitials: conn.avatarInitials,
                    authorAvatarTopHex: conn.avatarTopHex,
                    authorAvatarBottomHex: conn.avatarBottomHex,
                    content: text,
                    timestamp: post.timestamp.addingTimeInterval(Double(i + 1) * 3600),
                    likeCount: Int.random(in: 0...24)
                ))
            }
            result[post.id] = comments
        }
        return result
    }
